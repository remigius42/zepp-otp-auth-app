#!/usr/bin/env sh
# Generates the third-party license data rendered by the Settings App's license
# section. Output is generated, gitignored and never committed.

set -eu

readonly LICENSE_FILE="./src/setting/licenses.js"

printf "/* generated by npm run generate-licenses-data */\n// prettier-ignore\nexport default" > "${LICENSE_FILE}"
npx license-checker-rseidelsohn \
  --customPath .license-checker-format.json \
  --json --production --excludePrivatePackages >> "${LICENSE_FILE}"
